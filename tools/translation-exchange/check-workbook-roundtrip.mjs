import fs from 'node:fs/promises';
import os from 'node:os';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { parseRows, preview, rehearse } from './exchange.mjs';

const [folder, snapshotPath] = process.argv.slice(2);
if (!folder || !snapshotPath) throw new Error('Aufruf: check-workbook-roundtrip.mjs AUSGABEORDNER SNAPSHOT');
const loader = createRequire(resolve(folder, 'package.json'));
const { FileBlob, SpreadsheetFile } = await import(pathToFileURL(loader.resolve('@oai/artifact-tool')).href);
const input = resolve(folder, 'flashterm-fungi-uebersetzung-en-US.xlsx');
const job = JSON.parse(await fs.readFile(resolve(folder, 'auftrag/auftrag-intern.json'), 'utf8'));
const snapshot = JSON.parse(await fs.readFile(snapshotPath, 'utf8'));
const python = process.env.FLASHTERM_PYTHON || 'python3';
const reader = fileURLToPath(new URL('./read_xlsx.py', import.meta.url));
const read = path => JSON.parse(execFileSync(python, [reader, path], { encoding: 'utf8' }));
const result = { checks: [] };
const original = parseRows(job, read(input));
assert.equal(preview(job, original, snapshot, 'flashterm-fungi').rows.every(r => r.status === 'pending'), true);
result.checks.push('Unbearbeitete Excel-Datei: keine Änderungen');
const workbook = await SpreadsheetFile.importXlsx(await FileBlob.load(input));
const sheet = workbook.worksheets.getItem('Übersetzung');
const selected = job.rows.filter(r => r.conceptId === '100067');
for (const row of selected) {
    const n = job.rows.indexOf(row) + 10;
    sheet.getRange(`J${n}`).values = [[row.field === 'preferredTerm' ? 'shiitake' : 'TEST TRANSLATION: returned definition for the isolated roundtrip.']];
    sheet.getRange(`K${n}`).values = [['Fertig']];
}
workbook.recalculate();
const tmp = await fs.mkdtemp(resolve(os.tmpdir(), 'flashterm-translation-test-'));
const returnedPath = resolve(tmp, 'returned.xlsx');
await (await SpreadsheetFile.exportXlsx(workbook)).save(returnedPath);
const receipt = parseRows(job, read(returnedPath));
const review = preview(job, receipt, snapshot, 'flashterm-fungi');
assert.equal(review.rows.filter(r => r.status === 'ready').length, 2);
assert.equal(review.rows.filter(r => r.status === 'pending').length, 8);
const first = rehearse(job, receipt, snapshot, 'flashterm-fungi', selected.map(r => r.rowId));
assert.equal(first.journal.length, 2);
const second = rehearse(job, receipt, first.candidate, 'flashterm-fungi', selected.map(r => r.rowId));
assert.equal(second.journal.length, 0);
result.checks.push('XLSX-Rücklieferung: zwei Ergänzungen korrekt zugeordnet', 'Erneuter lokaler Import: null zusätzliche Änderungen');
sheet.getRange('J10').formulas = [['=1+1']];
workbook.recalculate();
const formulaPath = resolve(tmp, 'formula.xlsx');
await (await SpreadsheetFile.exportXlsx(workbook)).save(formulaPath);
assert.throws(() => read(formulaPath));
result.checks.push('Excel-Formeln werden vor der Verarbeitung abgewiesen');
result.filemakerChanged = false;
result.nativeExcelTested = false;
await fs.writeFile(resolve(folder, 'roundtrip-check.json'), JSON.stringify(result, null, 2) + '\n');
await fs.writeFile(resolve(folder, 'test-importvorschau.json'), JSON.stringify(review, null, 2) + '\n');
console.log(JSON.stringify(result));
